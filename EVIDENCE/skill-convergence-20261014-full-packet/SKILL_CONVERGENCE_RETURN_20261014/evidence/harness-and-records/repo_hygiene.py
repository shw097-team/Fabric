"""Repo hygiene pass: classify the working tree, scan every byte about to be committed, and write a manifest.

Two gates before a commit, per the publication discipline this stack follows: a secret scan of the exact bytes
that would leave the working tree, and a generated manifest carrying a hash for every file so a later reviewer
can prove the committed bytes were not edited on the way in. Junk is excluded by an explicit list, never
silently.

The scan is a smell test, not a proof: it looks for credential-shaped strings and for assignment patterns. A hit
aborts the whole pass rather than being committed and fixed later.
"""
import json,re,hashlib,pathlib,subprocess,sys,datetime
R=pathlib.Path('C:/Projects/Agent_Workspace/Fabric')
IGNORE_DIRS={'__pycache__','.git','runs'}
JUNK_DELETE_DIRS={'__pycache__'}
JUNK_SUFFIX={'.pyc','.pyo'}
GITIGNORE="""# Build and byte-cache artifacts: regenerable, never tracked.
__pycache__/
*.py[cod]
.pytest_cache/

# Run output from the autonomous research subsystem: regenerated by every run, tracked nowhere.
runs/

# Editor and OS noise.
.DS_Store
Thumbs.db
*.tmp
*.log
"""
SECRET_PATTERNS=[r'github_pat_[A-Za-z0-9_]{20,}',r'gh[pousr]_[A-Za-z0-9]{30,}',r'sk-[A-Za-z0-9]{20,}',
    r'-----BEGIN [A-Z ]*PRIVATE KEY-----',r'AKIA[0-9A-Z]{16}',r'xox[baprs]-[A-Za-z0-9-]{10,}',
    r'(?i)(api[_-]?key|password|passwd|secret|access[_-]?token)\s*[:=]\s*["\']?[A-Za-z0-9_\-]{16,}']
def porcelain():
    out=subprocess.run(['git','-C',str(R),'status','--porcelain'],capture_output=True,text=True,encoding='utf-8',errors='replace').stdout
    rows=[]
    for line in out.splitlines():
        st,path=line[:2],line[3:]
        if path.startswith('"'):path=path.strip('"').encode('utf-8','surrogateescape').decode('unicode_escape')
        rows.append((st,path))
    return rows
rows=porcelain()
junk=[];keep=[];dirs=[];excluded=[]
for st,path in rows:
    p=R/path
    parts=set(path.replace('\\','/').split('/'))
    if (parts & IGNORE_DIRS) or p.suffix in JUNK_SUFFIX:
        (junk if (parts & JUNK_DELETE_DIRS) or p.suffix in JUNK_SUFFIX else excluded).append(path)
        continue
    if p.is_dir():
        dirs.append((st,path))
        for sub in sorted(p.rglob('*')):
            if not sub.is_file():continue
            rel=sub.relative_to(R).as_posix()
            if set(rel.split('/')) & IGNORE_DIRS or sub.suffix in JUNK_SUFFIX:continue
            keep.append(('inside-untracked-dir',rel))
        continue
    keep.append((st,path))
scan=[];hits=[]
for st,path in keep:
    p=R/path
    try:data=p.read_bytes()
    except OSError as e:
        scan.append({'path':path,'read_error':str(e)});continue
    text=data.decode('utf-8','replace')
    found=[pat for pat in SECRET_PATTERNS if re.search(pat,text)]
    if found:hits.append({'path':path,'patterns':found})
    scan.append({'path':path,'git_state':st,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
(R/'.gitignore').write_text(GITIGNORE,encoding='utf-8',newline='\n')
removed=[]
for path in junk:
    p=R/path
    if p.is_file() and p.suffix in JUNK_SUFFIX:
        p.unlink();removed.append(path)
    elif p.is_dir():
        for sub in sorted(p.rglob('*'),reverse=True):
            if sub.is_file():sub.unlink()
        for sub in sorted([d for d in p.rglob('*') if d.is_dir()],reverse=True):sub.rmdir()
        try:p.rmdir()
        except OSError:pass
        removed.append(path)
man={'schema':'FABRIC-REPO-HYGIENE-MANIFEST/1','observed_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),
 'purpose':'classify the Fabric working tree, prove the pre-commit secret scan, and hash every file brought under version control',
 'counts':{'changed_or_untracked_entries':len(rows),'junk_removed':len(junk),'formerly_untracked_directories_expanded':len(dirs),
   'files_hashed':len(scan),'secret_hits':len(hits),'excluded_by_gitignore_not_deleted':len(excluded)},
 'junk_removed':sorted(junk),'excluded_by_gitignore_not_deleted':sorted(excluded),
 'formerly_untracked_directories_expanded':[d[1] for d in dirs],
 'files':sorted(scan,key=lambda x:x['path']),'secret_hits':hits,
 'policy':{'junk':'byte-cache directories and compiled artifacts are removed from the working tree and excluded by the new .gitignore; they are regenerable',
   'untracked_directories':'directories that were untracked are expanded and hashed file by file rather than swept in as opaque blobs',
   'runs_left_out':'the autonomous research subsystem\'s run output is excluded by .gitignore as regenerable run product, and is named here rather than hidden',
   'scan':'patterns for host tokens, cloud key ids, private-key headers and credential assignments; a hit aborts the commit',
   'hash':'sha256 of the file as it sits in the working tree at manifest time'},
 'claim_ceiling':'a hygiene and scan record for a local repository with no remote; it asserts nothing about whether the underlying content is correct'}
(R/'HYGIENE_MANIFEST_20261014.json').write_text(json.dumps(man,ensure_ascii=False,indent=2),encoding='utf-8',newline='\n')
after=porcelain()
print(json.dumps({'entries_before':len(rows),'junk_removed':len(removed),'dirs_expanded':len(dirs),'files_hashed':len(scan),
  'secret_hits':len(hits),'entries_after_cleanup':len(after)},indent=1))
print('JUNK_REMOVED',sorted(removed)[:8])
print('HITS',hits[:5])

